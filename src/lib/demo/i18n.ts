const dict = { en, ar };

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = dict[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const isKey = (k: string): k is Key => k in en;

export function fmtAED(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "ar" ? "ar-AE" : "en-AE", {
    style: "currency",
    currency: "AED",
    maximumFractionDigits: n % 1 ? 2 : 0,
  }).format(n);
}

export function fmtDate(ms: number, lang: Lang, withTime = false) {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-AE" : "en-GB", {
    timeZone: "Asia/Dubai",
    day: "numeric",
    month: "short",
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(ms);
}

export const fmtNum = (n: number, lang: Lang) => new Intl.NumberFormat(lang === "ar" ? "ar-AE" : "en-US").format(n);
